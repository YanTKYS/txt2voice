using TxtToVoice.Services;
using Xunit;

namespace TxtToVoice.Tests.Golden
{
    /// <summary>
    /// TextPreprocessor 行政文書ゴールデンテスト（#62）。
    /// 自治体文書に近い文レベルで全フェーズの変換を回帰テストとして固定する。
    /// </summary>
    public class TextPreprocessorGoldenTests
    {
        // ================================================================
        // S1: 月 × 時刻 複合（フェーズ1 + フェーズ4）
        // ================================================================

        [Theory]
        [InlineData(
            "令和6年4月1日より、市役所の窓口受付時間は9時から17時となります。",
            "令和6年しがつ1日より、市役所の窓口受付時間はくじからじゅうしちじとなります。")]
        [InlineData(
            "保育所入所の申込受付は10時から12時と14時から17時です。",
            "保育所入所の申込受付はじゅうじからじゅうにじとじゅうよじからじゅうしちじです。")]
        [InlineData(
            "市民向け説明会は第2回として3月10日（月）10時30分に開催されます。",
            "市民向け説明会はだいにかいとしてさんがつ10日（月）じゅうじさんじゅっぷんに開催されます。")]
        public void Golden_S1_月と時刻の複合変換(string input, string expected)
        {
            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }

        // ================================================================
        // S2: 記号 × パーセント（フェーズ1 + フェーズ2）
        // ================================================================

        [Theory]
        [InlineData(
            "消費税率は10%です。令和5年10月1日から変更はありません。",
            "消費税率は10パーセントです。令和5年じゅうがつ1日から変更はありません。")]
        [InlineData(
            "令和5年度の施設利用率は95%で、前年比103%の実績となりました。",
            "令和5年度の施設利用率は95パーセントで、前年比103パーセントの実績となりました。")]
        [InlineData(
            "〒100-0001の千代田区では気温25℃を記録し、50㎡以上の物件が増加しています。",
            "ゆうびんばんごう100-0001の千代田区では気温25どを記録し、50へいほうめーとる以上の物件が増加しています。")]
        public void Golden_S2_記号とパーセント変換(string input, string expected)
        {
            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }

        // ================================================================
        // S3: 電話番号 × 第X回 × Xか月（フェーズ3）
        // ================================================================

        [Theory]
        [InlineData(
            "救急搬送の連絡先は090-1234-5678または03-5678-9012です。",
            "救急搬送の連絡先は090の1234の5678または03の5678の9012です。")]
        [InlineData(
            "第3回定例議会は7月20日から7月31日の予定です。",
            "だいさんかい定例議会はしちがつ20日からしちがつ31日の予定です。")]
        [InlineData(
            "育児休業は最長3か月の延長が可能です。次回審議は第10回委員会で行います。",
            "育児休業は最長さんかげつの延長が可能です。次回審議はだいじゅうかい委員会で行います。")]
        public void Golden_S3_電話番号と慣用表現変換(string input, string expected)
        {
            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }

        // ================================================================
        // S4: コロン時刻（フェーズ5 → フェーズ4 連鎖）
        // ================================================================

        [Theory]
        [InlineData(
            "受付時間は9:00から17:30です。",
            "受付時間はくじぜろふんからじゅうしちじさんじゅっぷんです。")]
        [InlineData(
            "開庁時間は8:30から17:15です。昼休みは12:00から13:00となります。",
            "開庁時間ははちじさんじゅっぷんからじゅうしちじじゅうごふんです。昼休みはじゅうにじぜろふんからじゅうさんじぜろふんとなります。")]
        [InlineData(
            "窓口受付は9:00〜17:00。土曜は9:00〜12:00。",
            "窓口受付はくじぜろふん〜じゅうしちじぜろふん。土曜はくじぜろふん〜じゅうにじぜろふん。")]
        public void Golden_S4_コロン時刻の展開と読み仮名変換(string input, string expected)
        {
            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }

        // ================================================================
        // S5: 除外ケース（変換してはいけないパターン）
        // ================================================================

        [Theory]
        [InlineData(
            "完成には10時間かかります。申請期間は3か月以内です。",
            "完成には10時間かかります。申請期間はさんかげつ以内です。")]
        [InlineData(
            "2024-01-01から2024-12-31まで有効です。",
            "2024-01-01から2024-12-31まで有効です。")]
        public void Golden_S5_除外ケースは変換しない(string input, string expected)
        {
            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }

        // ================================================================
        // S6: 全フェーズ混合（総合文書）
        // ================================================================

        [Fact]
        public void Golden_S6_行政文書全フェーズ混合()
        {
            string input =
                "令和6年4月から〒530-0001の大阪市北区役所（Tel:06-4301-3131）で、" +
                "第1回住民説明会を10:00から12時まで開催します。" +
                "参加費は無料、定員50名。詳細は3月末までに市報で告知予定。";

            string expected =
                "令和6年しがつから" +
                "ゆうびんばんごう530-0001の大阪市北区役所（Tel:06の4301の3131）で、" +
                "だいいちかい住民説明会をじゅうじぜろふんからじゅうにじまで開催します。" +
                "参加費は無料、定員50名。詳細はさんがつ末までに市報で告知予定。";

            Assert.Equal(expected, TextPreprocessor.Apply(input));
        }
    }
}
